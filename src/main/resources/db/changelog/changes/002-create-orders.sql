CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    total_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT chk_orders_total_price CHECK (total_price >= 0)
);

CREATE INDEX idx_orders_user_id ON orders (user_id) WHERE deleted = FALSE;
CREATE INDEX idx_orders_status ON orders (status) WHERE deleted = FALSE;
CREATE INDEX idx_orders_created_at ON orders (created_at) WHERE deleted = FALSE;
